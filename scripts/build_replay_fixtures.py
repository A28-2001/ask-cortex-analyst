"""Build chainlit_app/replay.json from the recorded evaluation runs.

When the live warehouse is unavailable (trial ended, the resource monitor
suspended it at its monthly quota, or an outage) the chat falls back to these
recordings instead of failing. Every entry is a real response: the question
exactly as it was asked during the evaluation, the SQL Cortex Analyst
generated, its interpretation text, and the rows Snowflake actually returned.
Nothing is written by hand.

The eval files store rows but not column names, so the column names are
recovered by parsing the outermost SELECT of each recorded statement. Every
recovered list is checked against the width of the recorded rows; the build
fails loudly rather than shipping a mislabelled answer.

Run:  python scripts/build_replay_fixtures.py
"""

import datetime as dt
import decimal
import json
import os
import re
import subprocess

import sys

import sqlglot
import yaml

ROOT = os.path.join(os.path.dirname(__file__), "..")
sys.path.insert(0, ROOT)

# Same normalizer the app uses at lookup time, so the stored keys and the
# runtime lookups can never drift apart.
from chainlit_app.replay import normalize  # noqa: E402
OUT = os.path.join(ROOT, "chainlit_app", "replay.json")

# (file, which part of the evaluation it came from)
SOURCES = [
    ("eval/cortex_analyst_results.yaml", "the 36-question benchmark"),
    ("eval/holdout_results.yaml", "the blind holdout set"),
    ("eval/stress_test_cortex_results.yaml", "the adversarial stress test"),
]

REQUEST_ID_COMMENT = re.compile(r"\s*--\s*Generated by Cortex Analyst.*$", re.MULTILINE)


class _EvalLoader(yaml.SafeLoader):
    """safe_load plus the one Python tag the holdout run wrote (Decimal)."""


_EvalLoader.add_constructor(
    "tag:yaml.org,2002:python/object/apply:decimal.Decimal",
    lambda loader, node: decimal.Decimal(loader.construct_sequence(node)[0]),
)


def recorded_on(path: str) -> str:
    """Month the recording was committed, from git, for the on screen label."""
    try:
        iso = subprocess.run(
            ["git", "log", "-1", "--format=%cI", "--", path],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
        return dt.datetime.fromisoformat(iso).strftime("%B %Y")
    except Exception:
        return "July 2026"


def to_json_value(v):
    if isinstance(v, decimal.Decimal):
        return float(v)
    if isinstance(v, (dt.date, dt.datetime)):
        return v.isoformat()
    return v


def output_columns(sql: str):
    tree = sqlglot.parse_one(sql, read="snowflake")
    return [e.alias_or_name.upper() for e in tree.selects]


def build():
    entries, seen = [], set()
    for path, origin in SOURCES:
        when = recorded_on(path)
        records = yaml.load(open(os.path.join(ROOT, path)), Loader=_EvalLoader)["results"]
        for r in records:
            question, sql, rows = r["question"], r.get("generated_sql"), r.get("actual_rows")
            # An eval script re-run against an unavailable account writes the
            # API error in place of the response. Replaying that as if it were
            # Cortex Analyst's answer would be the worst possible outcome, so
            # refuse to build from damaged recordings instead.
            if "API_ERROR" in str(r.get("cortex_text") or "") or r.get("exec_error"):
                raise SystemExit(
                    f"{path} {r['id']}: recording contains an error instead of a "
                    "response. Restore the file from git before building."
                )
            key = normalize(question)
            if key in seen:
                continue

            if not sql:
                # A refusal: Cortex Analyst declined to write SQL at all.
                entry = {"kind": "refusal"}
            elif isinstance(rows, list):
                cols = output_columns(sql)
                width = len(rows[0]) if rows else len(cols)
                if not cols or "*" in cols or len(cols) != width:
                    raise SystemExit(f"{r['id']}: recovered columns {cols} do not match row width {width}")
                entry = {
                    "kind": "data",
                    "sql": REQUEST_ID_COMMENT.sub("", sql).strip(),
                    "columns": cols,
                    "rows": [[to_json_value(v) for v in row] for row in rows],
                }
            else:
                # SQL was generated but its rows weren't recorded, so there is
                # no honest way to replay the answer. Leave it out.
                continue

            entry.update({
                "id": r["id"],
                "question": question,
                "key": key,
                "text": r.get("cortex_text") or "",
                "origin": origin,
                "recorded": when,
            })
            entries.append(entry)
            seen.add(key)

    with open(OUT, "w") as f:
        json.dump({"entries": entries}, f, indent=1, ensure_ascii=False)
    kinds = {k: sum(e["kind"] == k for e in entries) for k in ("data", "refusal")}
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(entries)} answers {kinds}")


if __name__ == "__main__":
    build()
